#!/usr/bin/env bash
# The one command before `git push origin HEAD:develop` (#2079).
#
# The pre-push hook no longer runs t0; it accepts a push only when t0 has passed
# for the exact tree. This script gets the tree to that state in the order that
# makes a failure cheap, and says what it is doing at each step:
#
#   1. range         the commits being pushed (origin/develop..HEAD)
#   2. asymmetry     #618 over that range, first: seconds, and the most common
#                    refusal. On failure it stops and names the split.
#   3. evidence      regenerates the registry and architecture artifacts ONCE,
#                    after the code commits they index, and commits them last.
#                    Regenerating mid-rework is what left them stale before.
#   4. fast gates    redaction-oracles, pdf-capability-registry,
#                    doc-claim-freshness: under a minute together, before the
#                    ~3 minute build-and-test rows.
#   5. t0            scripts/test-tier.sh t0, which records the pass the hook reads
#                    and writes logs/t0-latest/summary.txt.
#
# It never pushes. It ends by printing the push command, or the step that failed
# and the log to read.
#
# Usage: scripts/prepare-push.sh [--no-evidence-commit]
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || exit 1
[ -d "$HOME/.dotnet" ] && export PATH="$HOME/.dotnet:$PATH"

COMMIT_EVIDENCE=1
case "${1:-}" in
    --no-evidence-commit) COMMIT_EVIDENCE=0 ;;
    "") ;;
    *) echo "usage: $0 [--no-evidence-commit]" >&2; exit 2 ;;
esac

LOG="$ROOT/logs/prepare-push_$(date +%Y%m%d_%H%M%S).log"
mkdir -p "$ROOT/logs"
step() { printf '\n== [%s/5] %s\n' "$1" "$2" | tee -a "$LOG"; }
stop() { printf '\nprepare-push: STOPPED at step %s — %s\n  log: %s\n' "$1" "$2" "$LOG" | tee -a "$LOG"; exit 1; }

if [ -n "$(git status --porcelain --untracked-files=no)" ]; then
    echo "prepare-push: the tree has uncommitted tracked changes; commit or stash them first." >&2
    git status --short --untracked-files=no >&2
    exit 1
fi

step 1 "range"
base="$(git merge-base origin/develop HEAD 2>/dev/null)" || stop 1 "no merge base with origin/develop (fetch first)"
count="$(git rev-list --count "$base..HEAD")"
git log --oneline "$base..HEAD" | tee -a "$LOG"
[ "$count" -gt 0 ] || stop 1 "nothing to push: HEAD is already on origin/develop"
echo "$count commit(s) on top of origin/develop" | tee -a "$LOG"

step 2 "gate-asymmetry over $base..HEAD (#618)"
asym_ok() { GATE_ASYMMETRY_HEAD="$(git rev-parse "$2")" scripts/check-gate-asymmetry.sh "$1" >>"$LOG" 2>&1; }
SPLIT=""
if asym_ok "$base" HEAD; then
    echo "  PASS — one push" | tee -a "$LOG"
else
    # The range mixes a perf-path change with a rewritten expectation, so it must
    # go as two pushes. Find the split point: a commit C with base..C and C..HEAD
    # each passing. Both pushes are then accepted against the SAME t0 pass (the
    # hook tests the working tree, HEAD, and judges each push's own range).
    for c in $(git rev-list --reverse "$base..HEAD~1"); do
        if asym_ok "$base" "$c" && asym_ok "$c" HEAD; then SPLIT="$c"; break; fi
    done
    [ -n "$SPLIT" ] || stop 2 "no single split point makes both ranges pass; reorder the commits so the perf-path ones come last (or first), then re-run"
    echo "  needs TWO pushes; split after $(git log -1 --format='%h %s' "$SPLIT")" | tee -a "$LOG"
fi

step 3 "derived evidence (registry, architecture)"
if ! scripts/check-pdf-capability-registry.sh --update >>"$LOG" 2>&1; then
    stop 3 "registry regeneration failed"
fi
if ! scripts/check-architecture-artifacts.sh --update >>"$LOG" 2>&1; then
    tail -15 "$LOG"
    stop 3 "architecture artifact regeneration failed (a new unreachable symbol needs a decision in tests/reachability-baseline.tsv?)"
fi
if [ -n "$(git status --porcelain --untracked-files=no)" ]; then
    git status --short --untracked-files=no | tee -a "$LOG"
    if [ "$COMMIT_EVIDENCE" = 1 ]; then
        msg="$(mktemp)"
        printf 'chore(evidence): registry and architecture artifacts\n\nRegenerated by scripts/prepare-push.sh for the commits below it.\n' > "$msg"
        git add -u && git commit -q -F "$msg" && rm -f "$msg" || stop 3 "could not commit the regenerated evidence"
        echo "  committed $(git log -1 --format='%h %s')" | tee -a "$LOG"
    else
        stop 3 "the evidence changed; commit it (or re-run without --no-evidence-commit)"
    fi
else
    echo "  already current" | tee -a "$LOG"
fi

step 4 "fast gates"
for gate in check-redaction-oracles.sh check-pdf-capability-registry.sh check-doc-claim-freshness.sh; do
    start=$(date +%s)
    if scripts/$gate >>"$LOG" 2>&1; then
        echo "  PASS $gate ($(( $(date +%s) - start ))s)" | tee -a "$LOG"
    else
        tail -25 "$LOG"
        stop 4 "$gate failed"
    fi
done

step 5 "t0 (about 3 minutes; result in logs/t0-latest/summary.txt)"
scripts/test-tier.sh t0 >>"$LOG" 2>&1
rc=$?
if [ "$rc" != 0 ]; then
    sed -n '1,60p' "$ROOT/logs/t0-latest/summary.txt" 2>/dev/null
    stop 5 "t0 failed (rc=$rc); summary: logs/t0-latest/summary.txt"
fi
echo "  PASS — pass recorded for this tree" | tee -a "$LOG"

if [ -n "$SPLIT" ]; then
    printf '\nprepare-push: READY. Push in two steps (each is accepted against this pass; no re-run):\n    git push origin %s:develop\n    git push origin HEAD:develop\n' \
        "$(git rev-parse --short "$SPLIT")" | tee -a "$LOG"
else
    printf '\nprepare-push: READY. Push with:\n    git push origin HEAD:develop\n' | tee -a "$LOG"
fi
